    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0) ; LEA_SYM(A1, a64_gc_ld) ; SX_VCALL(fprintf)
    LEA_SYM(A0, reg_x0) ; LD64(A1, S2, IR_DST) ; SX_CALL(sx_a64_st) ; JMP(.L_a64_next)
.L_a64_r8:
