    LD64(A0, S2, IR_SRC1) ; LEA_SYM(A1, reg_rax) ; SX_CALL(sx_x64_load_vreg)
    LD64(A0, S2, IR_SRC2) ; LEA_SYM(A1, reg_r10) ; SX_CALL(sx_x64_load_vreg)
