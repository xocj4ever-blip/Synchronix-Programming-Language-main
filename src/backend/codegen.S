    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0) ; LEA_SYM(A1, a64_jmp) ; LD64(A2, S2, IR_DST) ; SX_VCALL(fprintf)
    JMP(.L_a64_next)
.L_a64_brz:
    CMPI(S3, IR_BRZ) ; JNE(.L_a64_arg)
    LD64(A0, S2, IR_SRC1) ; LEA_SYM(A1, reg_x0) ; SX_CALL(sx_a64_ld)
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0) ; LEA_SYM(A1, a64_brz) ; LD64(A2, S2, IR_DST) ; SX_VCALL(fprintf)
    JMP(.L_a64_next)
.L_a64_arg:
    CMPI(S3, IR_ARG) ; JNE(.L_a64_call)
    LD64(T0, S2, IR_IMM) ; LD64(T1, S2, IR_SRC1)
    LEA_SYM(R0, g_emit_arg_vregs) ; ST64_IDX(T1, R0, T0)
    JMP(.L_a64_next)
.L_a64_call:
    CMPI(S3, IR_CALL) ; JNE(.L_a64_ret)
    MOVI(S4, 0)
.L_a64_ca:
    LD64(T0, S2, IR_IMM) ; CMP(S4, T0) ; JGE(.L_a64_cgo)
    MOVR(A0, S4) ; SX_CALL(sx_a64_arg_name) ; MOVR(A1, R0)
    LEA_SYM(T1, g_emit_arg_vregs) ; LD64_IDX(A0, T1, S4) ; SX_CALL(sx_a64_ld)
    ADDI(S4, 1) ; JMP(.L_a64_ca)
.L_a64_cgo:
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0) ; LEA_SYM(A1, a64_call) ; LD64(A2, S2, IR_SRC2) ; LD64(A3, S2, IR_SRC1) ; SX_VCALL(fprintf)
    LEA_SYM(A0, reg_x0) ; LD64(A1, S2, IR_DST) ; SX_CALL(sx_a64_st)
    JMP(.L_a64_next)
.L_a64_ret:
    CMPI(S3, IR_RET) ; JNE(.L_a64_rt)
    LD64(A0, S2, IR_SRC1) ; LEA_SYM(A1, reg_x0) ; SX_CALL(sx_a64_ld)
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0) ; LEA_SYM(A1, a64_ret_jmp)
    LEA_SYM(T1, g_emit_cur_fn) ; LD64(A2, T1, 0) ; SX_VCALL(fprintf)
    JMP(.L_a64_next)

.L_a64_rt:
    CMPI(S3, IR_ARC_NEW) ; JNE(.L_a64_r1)
    LD64(A0, S2, IR_SRC1) ; LEA_SYM(A1, reg_x0) ; SX_CALL(sx_a64_ld)
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0) ; LEA_SYM(A1, a64_arc_new) ; SX_VCALL(fprintf)
    LEA_SYM(A0, reg_x0) ; LD64(A1, S2, IR_DST) ; SX_CALL(sx_a64_st) ; JMP(.L_a64_next)
.L_a64_r1:
    CMPI(S3, IR_ARC_RETAIN) ; JNE(.L_a64_r2)
    LD64(A0, S2, IR_SRC1) ; LEA_SYM(A1, reg_x0) ; SX_CALL(sx_a64_ld)
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0) ; LEA_SYM(A1, a64_arc_ret) ; SX_VCALL(fprintf) ; JMP(.L_a64_next)
