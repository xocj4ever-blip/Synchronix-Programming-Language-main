    LEA_SYM(A1, x64_mov_imm) ; LD64(A2, S2, IR_IMM) ; SX_VCALL(fprintf)
    LEA_SYM(A0, reg_rax) ; LD64(A1, S2, IR_DST) ; SX_CALL(sx_x64_store_vreg)
