SX_STR(ll_cmt2, " src1=v%lld src2=v%lld\n")
SX_STR(ll_const,"  %%t_%lld = add i64 0, %lld\n")

SX_TEXT
SX_FUNC(sx_codegen_llvm)
    SX_PROLOGUE 16
    LEA_SYM(T0, g_out_fp) ; ST64(A0, T0, 0)
    LEA_SYM(A1, ll_hdr1) ; SX_VCALL(fprintf)
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0)
    LEA_SYM(A1, ll_hdr2) ; SX_VCALL(fprintf)

    LEA_SYM(T0, g_ir_count) ; LD64(S0, T0, 0)
    MOVI(S1, 0)
.L_ll_loop:
    CMP(S1, S0) ; JGE(.L_ll_done)
    MOVR(S2, S1) ; SHLI(S2, 6) ; LEA_SYM(T0, g_ir_buf) ; ADD(S2, T0)
    LD64(T0, S2, IR_FLAGS) ; ANDI(T0, IRF_DEAD) ; CMPI(T0, 0) ; JNE(.L_ll_nxt)
    LD64(S3, S2, IR_OP)

    CMPI(S3, IR_FUNC_BEGIN) ; JNE(.L_ll_fend)
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0) ; LEA_SYM(A1, ll_fn_open)
    LD64(A2, S2, IR_SRC2) ; LD64(A3, S2, IR_SRC1) ; SX_VCALL(fprintf)
    LD64(S4, S2, IR_IMM)        /* param count */
    CMPI(S4, 1) ; JLT(.L_ll_fbody)
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0) ; LEA_SYM(A1, ll_p0) ; SX_VCALL(fprintf)
    CMPI(S4, 2) ; JLT(.L_ll_fbody)
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0) ; LEA_SYM(A1, ll_p1) ; SX_VCALL(fprintf)
    CMPI(S4, 3) ; JLT(.L_ll_fbody)
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0) ; LEA_SYM(A1, ll_p2) ; SX_VCALL(fprintf)
    CMPI(S4, 4) ; JLT(.L_ll_fbody)
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0) ; LEA_SYM(A1, ll_p3) ; SX_VCALL(fprintf)
.L_ll_fbody:
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0) ; LEA_SYM(A1, ll_fn_body) ; SX_VCALL(fprintf)
    JMP(.L_ll_nxt)

.L_ll_fend:
    CMPI(S3, IR_FUNC_END) ; JNE(.L_ll_inst)
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0) ; LEA_SYM(A1, ll_fn_close) ; SX_VCALL(fprintf)
    JMP(.L_ll_nxt)

.L_ll_inst:
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0) ; LEA_SYM(A1, ll_cmt1)
    MOVR(A2, S3) ; LD64(A3, S2, IR_DST) ; SX_VCALL(fprintf)
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0) ; LEA_SYM(A1, ll_cmt2)
    LD64(A2, S2, IR_SRC1) ; LD64(A3, S2, IR_SRC2) ; SX_VCALL(fprintf)

.L_ll_nxt:
    ADDI(S1, 1) ; JMP(.L_ll_loop)
.L_ll_done:
    MOVI(R0, 0)
    SX_EPILOGUE
SX_ENDFUNC(sx_codegen_llvm)
