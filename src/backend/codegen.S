.L_xb1: CMPI(S3, IR_MUL) ; JNE(.L_xb2) ; LEA_SYM(A1, x64_mul) ; JMP(.L_x64_bin_emit)
.L_xb2: CMPI(S3, IR_DIV) ; JNE(.L_xb3) ; LEA_SYM(A1, x64_div) ; JMP(.L_x64_bin_emit)
.L_xb3: CMPI(S3, IR_MOD) ; JNE(.L_xb4) ; LEA_SYM(A1, x64_mod) ; JMP(.L_x64_bin_emit)
.L_xb4: CMPI(S3, IR_CMP_EQ) ; JNE(.L_xb5) ; LEA_SYM(A1, x64_cmp_eq) ; JMP(.L_x64_bin_emit)
.L_xb5: CMPI(S3, IR_CMP_NE) ; JNE(.L_xb6) ; LEA_SYM(A1, x64_cmp_ne) ; JMP(.L_x64_bin_emit)
.L_xb6: CMPI(S3, IR_CMP_LT) ; JNE(.L_xb7) ; LEA_SYM(A1, x64_cmp_lt) ; JMP(.L_x64_bin_emit)
.L_xb7: CMPI(S3, IR_CMP_LE) ; JNE(.L_xb8) ; LEA_SYM(A1, x64_cmp_le) ; JMP(.L_x64_bin_emit)
.L_xb8: CMPI(S3, IR_CMP_GT) ; JNE(.L_xb9) ; LEA_SYM(A1, x64_cmp_gt) ; JMP(.L_x64_bin_emit)
.L_xb9: CMPI(S3, IR_CMP_GE) ; JNE(.L_xb10); LEA_SYM(A1, x64_cmp_ge) ; JMP(.L_x64_bin_emit)
.L_xb10:CMPI(S3, IR_AND)    ; JNE(.L_xb11); LEA_SYM(A1, x64_and)    ; JMP(.L_x64_bin_emit)
