    LD64(A0, S2, IR_SRC1) ; LEA_SYM(A1, reg_x0) ; SX_CALL(sx_a64_ld)
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0) ; LEA_SYM(A1, a64_gc_root) ; SX_VCALL(fprintf) ; JMP(.L_a64_next)
