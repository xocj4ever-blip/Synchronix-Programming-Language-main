/* ----------------------------------------------------------------------------
 * Helper: get x86_64 physical register name for index 0..4
 * ----------------------------------------------------------------------------
 */
SX_FUNC(sx_x64_phys_name)
    SX_PROLOGUE 0
    CMPI(A0, 0) ; JNE(.L_xp1) ; LEA_SYM(R0, x64_phys0) ; SX_EPILOGUE
.L_xp1: CMPI(A0, 1) ; JNE(.L_xp2) ; LEA_SYM(R0, x64_phys1) ; SX_EPILOGUE
.L_xp2: CMPI(A0, 2) ; JNE(.L_xp3) ; LEA_SYM(R0, x64_phys2) ; SX_EPILOGUE
.L_xp3: CMPI(A0, 3) ; JNE(.L_xp4) ; LEA_SYM(R0, x64_phys3) ; SX_EPILOGUE
.L_xp4: LEA_SYM(R0, x64_phys4) ; SX_EPILOGUE
SX_ENDFUNC(sx_x64_phys_name)

SX_FUNC(sx_x64_arg_name)
    SX_PROLOGUE 0
    CMPI(A0, 0) ; JNE(.L_xa1) ; LEA_SYM(R0, x64_arg0) ; SX_EPILOGUE
.L_xa1: CMPI(A0, 1) ; JNE(.L_xa2) ; LEA_SYM(R0, x64_arg1) ; SX_EPILOGUE
.L_xa2: CMPI(A0, 2) ; JNE(.L_xa3) ; LEA_SYM(R0, x64_arg2) ; SX_EPILOGUE
.L_xa3: LEA_SYM(R0, x64_arg3) ; SX_EPILOGUE
SX_ENDFUNC(sx_x64_arg_name)

/* ----------------------------------------------------------------------------
 * x86_64 vreg load/store helpers (uses Register Allocation when phys >= 0!)
 * sx_x64_load_vreg(A0 = vreg, A1 = target_reg_cstr)
 * ----------------------------------------------------------------------------
 */
SX_FUNC(sx_x64_load_vreg)
    SX_PROLOGUE 16
    MOVR(S0, A0)                /* vreg */
    MOVR(S1, A1)                /* target reg cstr */
    CMPI(S0, 256) ; JGE(.L_xlv_slot)
    LEA_SYM(T0, g_emit_vphys) ; LD64_IDX(S2, T0, S0)
    CMPI(S2, 0) ; JLT(.L_xlv_slot)
    /* Register allocated! movq %phys, %target */
    MOVR(A0, S2) ; SX_CALL(sx_x64_phys_name)
    MOVR(A2, R0)
    MOVR(A3, S1)
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0)
    LEA_SYM(A1, x64_ld_phys)
    SX_VCALL(fprintf)
    MOVI(R0, 0) ; SX_EPILOGUE
.L_xlv_slot:
    /* Stack slot: -(48 + vreg * 8)(%rbp) */
    MOVR(A2, S0) ; SHLI(A2, 3) ; ADDI(A2, 48)
    MOVR(A3, S1)
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0)
    LEA_SYM(A1, x64_ld_slot)
    SX_VCALL(fprintf)
    MOVI(R0, 0) ; SX_EPILOGUE
SX_ENDFUNC(sx_x64_load_vreg)

/* sx_x64_store_vreg(A0 = src_reg_cstr, A1 = vreg) */
SX_FUNC(sx_x64_store_vreg)
    SX_PROLOGUE 16
    MOVR(S0, A0)                /* src reg cstr */
    MOVR(S1, A1)                /* vreg */
    CMPI(S1, 256) ; JGE(.L_xsv_slot)
    LEA_SYM(T0, g_emit_vphys) ; LD64_IDX(S2, T0, S1)
    CMPI(S2, 0) ; JLT(.L_xsv_slot)
    MOVR(A0, S2) ; SX_CALL(sx_x64_phys_name)
    MOVR(A3, R0)
    MOVR(A2, S0)
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0)
    LEA_SYM(A1, x64_st_phys)
    SX_VCALL(fprintf)
    MOVI(R0, 0) ; SX_EPILOGUE
.L_xsv_slot:
    MOVR(A3, S1) ; SHLI(A3, 3) ; ADDI(A3, 48)
    MOVR(A2, S0)
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0)
    LEA_SYM(A1, x64_st_slot)
    SX_VCALL(fprintf)
    MOVI(R0, 0) ; SX_EPILOGUE
SX_ENDFUNC(sx_x64_store_vreg)

/* ============================================================================
 * 1. Custom x86_64 Native Assembly Emitter: sx_codegen_x86_64(A0 = FILE*)
 * ============================================================================
 */
SX_FUNC(sx_codegen_x86_64)
    SX_PROLOGUE 48
    LEA_SYM(T0, g_out_fp) ; ST64(A0, T0, 0)

    /* Header & String Literals */
    LEA_SYM(A1, x64_hdr) ; SX_VCALL(fprintf)

    LEA_SYM(T0, g_str_count) ; LD64(S0, T0, 0)
    MOVI(S1, 0)
.L_x64_strs:
    CMP(S1, S0) ; JGE(.L_x64_text)
    MOVR(S2, S1) ; SHLI(S2, 4) ; LEA_SYM(T0, g_strings) ; ADD(S2, T0)
    /* Emit .Lstr_i: .asciz "..." safely using 3-arg fprintf calls */
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0)
    LEA_SYM(A1, fmt_lstr_lbl) ; MOVR(A2, S1) ; SX_VCALL(fprintf)
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0)
    LEA_SYM(A1, fmt_lstr_val)
    LD64(A2, S2, 8)             /* len (int for %.*s) */
    LD64(A3, S2, 0)             /* ptr */
    SX_VCALL(fprintf)
    ADDI(S1, 1)
    JMP(.L_x64_strs)

SX_RODATA
SX_STR(fmt_lstr_lbl,  ".Lstr_%lld:\n")
SX_STR(fmt_lstr_val,  "    .asciz \"%.*s\"\n")
SX_STR(fmt_fn_g1,     "\n.globl %.*s\n.p2align 4\n")
SX_STR(fmt_fn_g2,     "%.*s:\n")
SX_STR(fmt_cl_new1,   "    leaq %.*s(%%rip), %%rcx\n")
SX_STR(fmt_cl_new2,   "    movq $%lld, %%rdx\n    call sx_closure_alloc\n")
SX_STR(fmt_sp_1,      "    movq %%rax, %%rdx\n    leaq %.*s(%%rip), %%rcx\n    call sx_spawn\n")
SX_TEXT

.L_x64_text:
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0)
    LEA_SYM(A1, x64_text_hdr) ; SX_VCALL(fprintf)

    LEA_SYM(T0, g_ir_count) ; LD64(S0, T0, 0)   /* S0 = count */
    MOVI(S1, 0)                                  /* S1 = i */

.L_x64_loop:
    CMP(S1, S0) ; JGE(.L_x64_done)
    MOVR(S2, S1) ; SHLI(S2, 6) ; LEA_SYM(T0, g_ir_buf) ; ADD(S2, T0)
    LD64(T0, S2, IR_FLAGS)
    ANDI(T0, IRF_DEAD) ; CMPI(T0, 0) ; JNE(.L_x64_next)

    LD64(S3, S2, IR_OP)

    /* --- IR_FUNC_BEGIN --- */
    CMPI(S3, IR_FUNC_BEGIN) ; JNE(.L_x64_fend)
    LD64(T0, S2, IR_DST) ; LEA_SYM(T1, g_emit_cur_fn) ; ST64(T0, T1, 0)
    LEA_SYM(T1, g_emit_arg_cnt) ; MOVI(T0, 0) ; ST64(T0, T1, 0)

    /* Populate g_emit_vphys[0..255] for this function from IR_PHYS! */
    MOVI(T0, 0) ; LEA_SYM(T1, g_emit_vphys) ; MOVI(R0, -1)
.L_x64_clr_vp:
    CMPI(T0, 256) ; JGE(.L_x64_scan_vp)
    ST64_IDX(R0, T1, T0) ; ADDI(T0, 1) ; JMP(.L_x64_clr_vp)
.L_x64_scan_vp:
    MOVR(S4, S1) ; ADDI(S4, 1)
.L_x64_vp_loop:
    CMP(S4, S0) ; JGE(.L_x64_emit_pro)
    MOVR(T0, S4) ; SHLI(T0, 6) ; LEA_SYM(T1, g_ir_buf) ; ADD(T0, T1)
    LD64(R0, T0, IR_OP) ; CMPI(R0, IR_FUNC_END) ; JEQ(.L_x64_emit_pro)
    LD64(R0, T0, IR_PHYS) ; CMPI(R0, 0) ; JLT(.L_x64_vp_nxt)
    LD64(A0, T0, IR_DST)
    CMPI(A0, 0) ; JLE(.L_x64_vp_nxt)
    CMPI(A0, 256) ; JGE(.L_x64_vp_nxt)
    LEA_SYM(T1, g_emit_vphys) ; ST64_IDX(R0, T1, A0)
.L_x64_vp_nxt:
    ADDI(S4, 1) ; JMP(.L_x64_vp_loop)

.L_x64_emit_pro:
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0)
    LEA_SYM(A1, fmt_fn_g1) ; LD64(A2, S2, IR_SRC2) ; LD64(A3, S2, IR_SRC1)
    SX_VCALL(fprintf)
    LEA_SYM(T0, g_out_fp) ; LD64(A0, T0, 0)
