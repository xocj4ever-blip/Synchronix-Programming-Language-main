/* ============================================================================
 * SYNCHRONIX ECOSYSTEM — Cargo Package Manager & Build System (cargo_pkg.S)
 * ============================================================================
 * Implements Developer Ecosystem -> Cargo (Package Manager & Build System):
 *   - synchronix new <name>   : scaffolds Synchronix.toml + src/main.synchronix
 *   - synchronix build        : builds project from Synchronix.toml
 *   - synchronix run [file]   : compiles & executes native binary
 *   - synchronix test [file]  : verifies Phi proofs & runs test binary
 * ============================================================================
 */

#include "portable_asm.S"
#include "sx_defs.S"

SX_RODATA
SX_STR(mode_wb_c,    "w")
SX_STR(mode_rb_c,    "rb")
SX_STR(toml_name,    "Synchronix.toml")
SX_STR(main_src_rel, "src/main.synchronix")
SX_STR(bin_out_rel,  "synchronix_app.exe")

SX_STR(fmt_mkdir_1,  "mkdir \"%s\" 2>NUL")
SX_STR(fmt_mkdir_2,  "mkdir \"%s/src\" 2>NUL")
SX_STR(fmt_toml_p,   "%s/Synchronix.toml")
SX_STR(fmt_main_p,   "%s/src/main.synchronix")

SX_STR(tpl_toml,     "[package]\nname = \"%s\"\nversion = \"0.1.0\"\nedition = \"2026\"\nmemory_model = \"unified-arc-gc\"\n\n[dependencies]\nstd = \"1.0\"\n")
SX_STR(tpl_main,     "// Synchronix Project — Generated by `synchronix new`\nfunc main() -> Int {\n    let msg = \"Hello from Synchronix (Pure Portable Assembly)!\"\n    println(msg)\n    let box = arc(42)\n    let managed = gc(100)\n    prove 2 + 2 == 4\n    println(box + managed)\n    mem_stats()\n    return 0\n}\n")

SX_STR(msg_new_ok,   "[Synchronix Cargo] Created package '%s' (Synchronix.toml + src/main.synchronix)\n")
SX_STR(msg_bld_ok,   "[Synchronix Cargo] Build succeeded -> %s\n")
SX_STR(msg_no_toml,  "[Synchronix Cargo] Error: Synchronix.toml not found in current directory.\n")
SX_STR(msg_running,  "[Synchronix Cargo] Running %s...\n")
SX_STR(msg_test_ok,  "[Synchronix Cargo] All Phi formal proofs & runtime tests PASSED!\n")
SX_STR(fmt_run_cmd,  "\"%s\"")

SX_BSS
.p2align 4
SX_LABEL(g_cargo_buf1)
    .skip 512
SX_LABEL(g_cargo_buf2)
    .skip 512

SX_TEXT

/* ----------------------------------------------------------------------------
 * sx_cmd_new(A0 = project_name) -> R0 = 0 on success
 * ----------------------------------------------------------------------------
 */
SX_FUNC(sx_cmd_new)
    SX_PROLOGUE 32
    MOVR(S0, A0)

    /* mkdir <name> & mkdir <name>/src */
    LEA_SYM(A0, g_cargo_buf1) ; MOVI(A1, 512) ; LEA_SYM(A2, fmt_mkdir_1) ; MOVR(A3, S0)
    SX_VCALL(snprintf)
    LEA_SYM(A0, g_cargo_buf1) ; SX_CALL(system)

    LEA_SYM(A0, g_cargo_buf1) ; MOVI(A1, 512) ; LEA_SYM(A2, fmt_mkdir_2) ; MOVR(A3, S0)
    SX_VCALL(snprintf)
    LEA_SYM(A0, g_cargo_buf1) ; SX_CALL(system)

    /* Write <name>/Synchronix.toml */
    LEA_SYM(A0, g_cargo_buf1) ; MOVI(A1, 512) ; LEA_SYM(A2, fmt_toml_p) ; MOVR(A3, S0)
    SX_VCALL(snprintf)
    LEA_SYM(A0, g_cargo_buf1) ; LEA_SYM(A1, mode_wb_c) ; SX_CALL(fopen)
    CMPI(R0, 0) ; JEQ(.L_new_fail)
    MOVR(S1, R0)
    MOVR(A0, S1) ; LEA_SYM(A1, tpl_toml) ; MOVR(A2, S0) ; SX_VCALL(fprintf)
    MOVR(A0, S1) ; SX_CALL(fclose)

    /* Write <name>/src/main.synchronix */
    LEA_SYM(A0, g_cargo_buf2) ; MOVI(A1, 512) ; LEA_SYM(A2, fmt_main_p) ; MOVR(A3, S0)
    SX_VCALL(snprintf)
    LEA_SYM(A0, g_cargo_buf2) ; LEA_SYM(A1, mode_wb_c) ; SX_CALL(fopen)
    CMPI(R0, 0) ; JEQ(.L_new_fail)
    MOVR(S1, R0)
    MOVR(A0, S1) ; LEA_SYM(A1, tpl_main) ; SX_VCALL(fprintf)
    MOVR(A0, S1) ; SX_CALL(fclose)

    LEA_SYM(A0, msg_new_ok) ; MOVR(A1, S0) ; SX_VCALL(printf)
    MOVI(R0, 0) ; SX_EPILOGUE
.L_new_fail:
    MOVI(R0, 1) ; SX_EPILOGUE
SX_ENDFUNC(sx_cmd_new)

/* ----------------------------------------------------------------------------
 * sx_cmd_build(A0 = optional_src_path_or_0, A1 = optional_out_path_or_0)
 * ----------------------------------------------------------------------------
 */
SX_FUNC(sx_cmd_build)
    SX_PROLOGUE 16
    MOVR(S0, A0)
    MOVR(S1, A1)
    CMPI(S0, 0) ; JNE(.L_bld_have_src)
    /* Verify Synchronix.toml exists */
    LEA_SYM(A0, toml_name) ; LEA_SYM(A1, mode_rb_c) ; SX_CALL(fopen)
    CMPI(R0, 0) ; JNE(.L_bld_toml_ok)
    LEA_SYM(A0, msg_no_toml) ; SX_VCALL(printf)
    MOVI(R0, 1) ; SX_EPILOGUE
.L_bld_toml_ok:
    MOVR(A0, R0) ; SX_CALL(fclose)
    LEA_SYM(S0, main_src_rel)
.L_bld_have_src:
    CMPI(S1, 0) ; JNE(.L_bld_go)
    LEA_SYM(S1, bin_out_rel)
.L_bld_go:
    MOVR(A0, S0) ; MOVR(A1, S1)
    SX_CALL(sx_compile_file)
    CMPI(R0, 0) ; JNE(.L_bld_ret)
    LEA_SYM(A0, msg_bld_ok) ; MOVR(A1, S1) ; SX_VCALL(printf)
    MOVI(R0, 0)
.L_bld_ret:
    SX_EPILOGUE
SX_ENDFUNC(sx_cmd_build)

/* ----------------------------------------------------------------------------
 * sx_cmd_run(A0 = optional_src_path_or_0) -> R0 = exit code
 * ----------------------------------------------------------------------------
 */
SX_FUNC(sx_cmd_run)
    SX_PROLOGUE 16
    LEA_SYM(A1, bin_out_rel)
    SX_CALL(sx_cmd_build)
    CMPI(R0, 0) ; JNE(.L_run_ret)
    LEA_SYM(A0, msg_running) ; LEA_SYM(A1, bin_out_rel) ; SX_VCALL(printf)
    LEA_SYM(A0, g_cargo_buf1) ; MOVI(A1, 512)
    LEA_SYM(A2, fmt_run_cmd) ; LEA_SYM(A3, bin_out_rel)
    SX_VCALL(snprintf)
    LEA_SYM(A0, g_cargo_buf1) ; SX_CALL(system)
.L_run_ret:
    SX_EPILOGUE
SX_ENDFUNC(sx_cmd_run)

/* ----------------------------------------------------------------------------
 * sx_cmd_test(A0 = optional_src_path_or_0)
 * ----------------------------------------------------------------------------
 */
SX_FUNC(sx_cmd_test)
    SX_PROLOGUE 16
    SX_CALL(sx_cmd_run)
    CMPI(R0, 0) ; JNE(.L_tst_ret)
    LEA_SYM(A0, msg_test_ok) ; SX_VCALL(printf)
    MOVI(R0, 0)
.L_tst_ret:
    SX_EPILOGUE
SX_ENDFUNC(sx_cmd_test)
